/**
 * CENTRAL PLATFORM CAPABILITY REGISTRY
 * 
 * Defines official capabilities, limits, aspect ratios, fields, and publishing
 * capabilities for every social platform and content format.
 * Zero invented capabilities — strictly grounded in official platform behaviors.
 */

export type PlatformId = "instagram" | "facebook" | "pinterest" | "linkedin" | "tiktok" | "youtube" | "x";

export type FormatCategory = "organic" | "ads";

export type MediaType = "image" | "video" | "multi_image" | "carousel" | "document" | "text_only";

export type AspectRatio = "1:1" | "9:16" | "16:9" | "4:5" | "2:3" | "1.91:1";

export type PublishingMode = "api_direct" | "manual_export" | "ads_manager" | "eligibility_required";

export interface PlatformCapability {
  platform: PlatformId;
  format: string;               // e.g. "Feed", "Reel", "Carousel", "Pin", "Idea Pin", "Document"
  formatKey: string;            // normalized identifier: "instagram_carousel"
  label: string;                // Display title: "Feed Carousel", "Standard Pin"
  category: FormatCategory;
  mediaType: MediaType;
  defaultAspectRatio: AspectRatio;
  supportedAspectRatios: AspectRatio[];
  maxMedia: number;             // e.g. 10 for IG Carousel, 1 for Feed
  minMedia: number;
  
  // Content Field Capabilities
  supportsTitle: boolean;
  supportsDescription: boolean;
  supportsCaption: boolean;
  supportsFirstComment: boolean;
  supportsHashtags: boolean;
  supportsDestinationUrl: boolean;
  supportsBoard: boolean;
  supportsTaggedTopics: boolean;
  supportsAltText: boolean;
  supportsProductTags: boolean;
  supportsStorySettings: boolean;
  supportsPrivacySettings: boolean;
  supportsDuetStitch: boolean;
  supportsAIModifiedDisclosure: boolean;
  supportsMultiSlide: boolean;
  supportsDocumentExport: boolean;

  // Character Limits
  titleLimit?: number;
  captionLimit: number;
  descriptionLimit?: number;
  altTextLimit?: number;
  firstCommentLimit: number;
  hashtagLimit: number;

  // API Publishing Status
  publishingMode: PublishingMode;
  publishingNotice?: string;

  // AI Generation Capabilities
  supportsAIImage: boolean;
  supportsAIVideo: boolean;
  supportsAICarousel: boolean;
  supportsAIDocument: boolean;
}

