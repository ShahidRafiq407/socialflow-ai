/**
 * Resolver function to get capability definition
 */
export function getPlatformCapability(platformId: string, formatName: string): PlatformCapability {
  const normPlatform = platformId.toLowerCase().trim();
  const directKey = `${normPlatform}:${formatName}`;

  if (PLATFORM_CAPABILITIES[directKey]) {
    return PLATFORM_CAPABILITIES[directKey];
  }

  // Fallback matching by format name variations
  const matchedKey = Object.keys(PLATFORM_CAPABILITIES).find(k => {
    const [p, f] = k.split(":");
    return p === normPlatform && (
      f.toLowerCase() === formatName.toLowerCase() ||
      formatName.toLowerCase().includes(f.toLowerCase()) ||
      f.toLowerCase().includes(formatName.toLowerCase())
    );
  });

  if (matchedKey && PLATFORM_CAPABILITIES[matchedKey]) {
    return PLATFORM_CAPABILITIES[matchedKey];
  }

  // Default fallback
  return {
    platform: normPlatform as PlatformId,
    format: formatName,
    formatKey: `${normPlatform}_${formatName.toLowerCase().replace(/\s+/g, "_")}`,
    label: `${formatName}`,
    category: "organic",
    mediaType: formatName.toLowerCase().includes("video") || formatName.toLowerCase().includes("reel") || formatName.toLowerCase().includes("short") ? "video" : formatName.toLowerCase().includes("carousel") || formatName.toLowerCase().includes("idea") ? "carousel" : "image",
    defaultAspectRatio: formatName.toLowerCase().includes("reel") || formatName.toLowerCase().includes("short") || formatName.toLowerCase().includes("story") ? "9:16" : "1:1",
    supportedAspectRatios: ["1:1", "9:16", "16:9"],
    maxMedia: 1,
    minMedia: 1,
    supportsTitle: false,
    supportsDescription: false,
    supportsCaption: true,
    supportsFirstComment: true,
    supportsHashtags: true,
    supportsDestinationUrl: false,
    supportsBoard: false,
    supportsTaggedTopics: false,
    supportsAltText: true,
    supportsProductTags: false,
    supportsStorySettings: false,
    supportsPrivacySettings: false,
    supportsDuetStitch: false,
    supportsAIModifiedDisclosure: false,
    supportsMultiSlide: false,
    supportsDocumentExport: false,
    captionLimit: 2200,
    firstCommentLimit: 1000,
    hashtagLimit: 30,
    publishingMode: "api_direct",
    supportsAIImage: true,
    supportsAIVideo: false,
    supportsAICarousel: false,
    supportsAIDocument: false,
  };
}
